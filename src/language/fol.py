"""
A base class for existential first order formulas
It supports the verification and query answering tasks given the formula
For the verification, there is no free_vars
For the query answering, there should be at least one free_vars
Several assumptions about the formula
- In DNF
- Only with existential quantifier
The query is generated by the following steps:

>>>> Construct the conjunctive query skeleton:
    1. Define the number of terms, including 
        - p existential vars
        - q free vars
        - r literals
        There are p + q + r terms
    2. Construct the edges between terms by random sampling, and then construct 
        a connective graph, the edge is constructed by the certain ratio $P_e$
    3. Randomly corrupt the edges with negation $P_n$
<<<< In this way, the conjunctive query skeleton is constructed

>>>> Construct the DNF formula
    The key of DNF construction is that there must be at least one variable be
    shared in two conjunctive query
    1. determin the variables to be shared (more than one)
    2. determin the objects to be shared (not necessary more than one)
<<<<

>>>> Sampling accross the graph
    1. For question answering task
        1. sample the full graph, 
            so that the predicates and objects are determined
        2. search over partial graph and full graph, 
            and find out the answer tuples
    2. Instantiation of the query graph 
<<<<
"""

from abc import abstractmethod, ABC
from ast import Str
import json
from msilib.schema import Binary
from typing import List


class Term(ABC):
    pass


class Variable(Term):
    EXIST = 1
    FREE = 2

    def __init__(self, varname, varstate) -> None:
        """
        varname: the name (identifier) of this variable
        varstate: the state (extential or not) of this variable
        """
        self.varname = varname
        self.varstate = varstate


class Literal(Term):
    def __init__(self, entity_id: int) -> None:
        """
        The id of the entities, -1 for placeholder
        """
        self.entity_id = entity_id


class Form:
    """
    Formula without quantifier information
    """
    pass

    @abstractmethod
    @classmethod
    def parse(cls):
        pass

    @abstractmethod
    def dumps(self):
        pass


class Atom(Form):
    """
    Binary predicate or negated binary predicate
    """
    pass

    @classmethod
    def parse(cls, atom_obj):
        assert atom_obj['type'] in ['neg', 'pred']
        if atom_obj['type'] == 'neg':
            return Negation.parse(atom_obj)
        if atom_obj['type'] == 'pred':
            return BinaryPredicate.parse(atom_obj)

class BinaryPredicate(Atom):
    def __init__(self, relation_id: int, term1: Term, term2: Term) -> None:
        self.relation_id = relation_id
        self.term1 = term1
        self.term2 = term2

    @classmethod
    def parse(cls, atom_obj):
        assert atom_obj['type'] == 'pred'
        pred, term1_obj, term2_obj = atom_obj['data']
        Term.parse

class Negation(Atom):
    def __init__(self, pred) -> None:
        self.pred = pred


class Conjunction(Form):
    def __init__(self, atoms: List[Atom]) -> None:
        self.atoms = atoms

    @classmethod
    def parse(cls, conj_obj):
        assert conj_obj['type'] == 'conj'
        atoms = [Atom.parse(atom_obj) for atom_obj in conj_obj['data']]
        return cls(atoms)


class DNF(Form):
    def __init__(self, conjunctions: List[Conjunction]) -> None:
        self.conjunction = conjunctions

    @classmethod
    def parse(cls, dnf_obj):
        assert dnf_obj['type'] == 'dnf'
        conjunctions = [Conjunction.parse(conj_obj) 
                        for conj_obj in dnf_obj['data']]
        return cls(conjunctions)

class Formula:
    """
    A base class for the string input of the entire formula structure
    """

    def __init__(self,
                 exist_vars: List[Str],
                 free_vars: List[Str],
                 literals: List[Str],
                 dnf: DNF):
        self.exist_vars = {v: Variable(v, Variable.EXIST) for v in exist_vars}
        self.free_vars = {v: Variable(v, Variable.FREE) for v in free_vars}
        self.literals = {v: Literal(int(v)) for v in literals}
        self.dnf = dnf

    @classmethod
    def loads(cls, s: Str):
        obj = json.loads(s)
        evars = obj['EVAR'].split(',')
        fvars = obj['FVAR'].split(',')
        ltrs = obj['LTR'].split(',')
        dnf_obj = obj['DNF']
        dnf = DNF.parse(dnf_obj)
        return cls(evars, fvars, ltrs, dnf)

    def dumps(self):
        obj = {
            'EVAR': ','.join([str(k) for k in self.exist_vars]),
            'FVAR': ','.join([str(k) for k in self.free_vars]),
            'LTR': ','.join([str(k) for k in self.literals]),
            'DNF': self.dnf.dumps()
        }
        return json.dumps(obj)
