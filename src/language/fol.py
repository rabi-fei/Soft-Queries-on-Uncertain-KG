def check_ldict(ldict):
    """
    Ldict is a nested dict that stores the GROUNDED information
    """
    assert 'op' in ldict
    op = ldict['op']
    assert 'args' in ldict
    args = ldict['args']

    if op == Term.op:
        assert 'name' in args
        assert 'state' in args
        assert 'entity_id_list' in args
    if op == BinaryPredicate.op:
        assert 'name' in args
        assert 'relation_id_list' in args
        check_ldict(args['term1'])
        check_ldict(args['term2'])
    if op == Negation.op:
        assert 'formula' in args
        check_ldict(args['formula'])
    if op == Conjunction.op or op == Disjunction.op:
        assert 'formulas' in args
        for f in args['formulas']:
            check_ldict(f)


def get_ldict(op, **args):
    ans = {'op': op, 'args': args}
    check_ldict(ans)
    return ans


class Lobject:
    @abstractmethod
    def to_ldict(self) -> Dict:
        pass

    @abstractmethod
    def to_lstr(self) -> str:
        pass

    def __repr__(self):
        check_ldict(self.to_ldict())
        return json.dumps(self.to_ldict(), indent=1)

    @abstractmethod
    def get_terms(self) -> Dict[str, 'Term']:
        pass

    @abstractmethod
    def get_predicates(self) -> Dict[str, 'BinaryPredicate']:
        pass

class Term(Lobject):
    EXISTENTIAL = 1
    FREE = 2
    UNIVERSAL = 3
    SYMBOL = 4

    op = "term"

    def __init__(self, state, name):
        self.state = state
        self.name = name
        self.entity_id_list = []

        self.batch_embedding = None
        self.batch_proposal_list = []

    @classmethod
    def parse(cls, ldict):
        op = ldict['op']
        assert op == cls.op
        args = ldict['args']
        name = args['name']
        state = args['state']
        object =  cls(name=name, state=state)
        object.entity_id_list = args['entity_id_list']
        return object

    def to_ldict(self):
        ldict = {'op': self.op,
                 'args': {
                   'state': self.state,
                   'name': self.name,
                   'entity_id_list': self.entity_id_list
                   }
              }
        return ldict

    def to_lstr(self) -> str:
        return self.name

    def get_terms(self) -> Dict[str, 'Term']:
        return {self.name: self}

    def get_predicates(self) -> Dict[str, 'BinaryPredicate']:
        return dict()

    def append_proposals(self, proposal):
        batch_size, embedding_dim = proposal.shape
        self.batch_proposal_list.append(
            proposal.view(batch_size, embedding_dim, 1))

