class Formula(Lobject):
    def __init__(self) -> None:
        super().__init__()

    @staticmethod
    def parse(ldict):
        op = ldict['op']
        if op == BinaryPredicate.op:
            return BinaryPredicate.parse(ldict)
        elif op == Negation.op:
            return Negation.parse(ldict)
        elif op == Conjunction.op:
            return Conjunction.parse(ldict)
        elif op == Disjunction.op:
            return Disjunction.parse(ldict)
        else:
            raise NotImplementedError("Unsupported Operator")


class BinaryPredicate(Formula):
    op = 'pred'

    def __init__(self,
                 name: str,
                 term1: Term,
                 term2: Term) -> None:
        self.name = name
        self.term1 = term1
        self.term2 = term2
        self.relation_id_list = []

    @classmethod
    def parse(cls, ldict):
        op = ldict['op']
        assert op == cls.op
        args = ldict['args']

        name = args['name']
        term1 = Term.parse(args['term1'])
        term2 = Term.parse(args['term2'])
        object = cls(name=name, term1=term1, term2=term2)
        object.relation_id_list = args['relation_id_list']
    def to_ldict(self):
        obj = {
            'op': self.op,
            'args': {
                'name': self.name,
                'relation_id_list': self.relation_id_list,
                'term1': self.term1.to_ldict(),
                'term2': self.term2.to_ldict()
            }
        }
        return obj

    def to_lstr(self):
        lstr = f"{self.name}({self.term1.name},{self.term2.name})"
        return lstr

    def get_terms(self) -> Dict[str, 'Term']:
        ans = {}
        ans.update(self.term1.get_terms())
        ans.update(self.term2.get_terms())
        return ans

    def get_predicates(self) -> Dict[str, 'BinaryPredicate']:
        ans = {self.name: self}
        return ans


class Negation(Formula):
    op = 'neg'
    def __init__(self, formula: Formula) -> None:
        self.formula = formula

    @classmethod
    def parse(cls, ldict):
        op = ldict['op']
        assert op == cls.op
        args = ldict['args']
        formula = Formula.parse(args['formula'])
        return cls(formula)

    def to_ldict(self):
        obj = {
            'op': self.op,
            'args': {'formula': self.formula.to_ldict()}
        }
        return obj

    def to_lstr(self) -> str:
        lstr = f"!({self.formula.to_lstr()})"
        return lstr

    def get_terms(self) -> Dict[str, 'Term']:
        ans = {}
        ans.update(self.formula.get_terms())
        return ans

    def get_predicates(self) -> Dict[str, 'BinaryPredicate']:
        ans = {}
        ans.update(self.formula.get_predicates())
        return ans

class Conjunction(Formula):
    op = 'conj'
    def __init__(self, formulas: List[Formula]) -> None:
        self.formulas = formulas

    @classmethod
    def parse(cls, ldict):
        op = ldict['op']
        assert op == cls.op
        args = ldict['args']
        formula_dict_list = args['formulas']
        formulas = [Formula.parse(formula_dict) for formula_dict in formula_dict_list]
        return cls(formulas)

    def to_ldict(self):
        obj = {
            'op': self.op,
            'args': {'formulas': [f.to_ldict() for f in self.formulas]}
        }
        return obj

    def to_lstr(self):
        lstr = "&".join(f"({f.to_lstr()})" for f in self.formulas)
        return lstr

    def get_terms(self) -> Dict[str, 'Term']:
        ans = {}
        for f in self.formulas:
            ans.update(f.get_terms())
        return ans

    def get_predicates(self) -> Dict[str, 'BinaryPredicate']:
        ans = {}
        for f in self.formulas:
            ans.update(f.get_predicates())
        return ans


