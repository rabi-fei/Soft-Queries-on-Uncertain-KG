"""
A base class for existential first order formulas
It supports the verification and query answering tasks given the formula
For the verification, there is no free_vars
For the query answering, there should be at least one free_vars
Several assumptions about the formula
- In DNF
- Only with existential quantifier
The query is generated by the following steps:

>>>> Construct the conjunctive query skeleton:
    1. Define the number of terms, including 
        - p existential vars
        - q free vars
        - r literals
        There are p + q + r terms
    2. Construct the edges between terms by random sampling, and then construct 
        a connective graph, the edge is constructed by the certain ratio $P_e$
    3. Randomly corrupt the edges with negation $P_n$
<<<< In this way, the conjunctive query skeleton is constructed

>>>> Construct the DNF formula
    The key of DNF construction is that there must be at least one variable be
    shared in two conjunctive query
    1. determin the variables to be shared (more than one)
    2. determin the objects to be shared (not necessary more than one)
<<<<

>>>> Sampling accross the graph
    1. For question answering task
        1. sample the full graph, 
            so that the predicates and objects are determined
        2. search over partial graph and full graph, 
            and find out the answer tuples
    2. Instantiation of the query graph 
<<<<
"""

from abc import abstractmethod
from collections import defaultdict
import json
from random import random, sample
from typing import Dict, List

import networkx as nx
from networkx.algorithms.components import connected_components


class Form:
    """
    Formula without quantifier information
    """
    pass

    @abstractmethod
    def parse(cls):
        pass

    @abstractmethod
    def to_dict(self) -> Dict:
        pass

    def __repr__(self):
        return json.dumps(self.to_dict())

    @abstractmethod
    def get_terms(self) -> Dict[str, Term]:
        pass


class Term(Form):
    @classmethod
    def parse(cls, term_obj):
        op = term_obj['op']
        assert op in ['var', 'ltr']
        if op == 'var':
            return Variable.parse(term_obj)
        if op == 'ltr':
            return Literal.parse(term_obj)


class Variable(Term):
    EXIST = 'EXIST'
    FREE = "FREE"

    def __init__(self, name, state) -> None:
        """
        varname: the name (identifier) of this variable
        varstate: the state (extential or not) of this variable
        """
        self.name = name
        self.state = state

    @classmethod
    def parse(cls, term_obj):
        op = term_obj['op']
        assert op == 'var'
        args = term_obj['args']
        name = args['name']
        state = args['state']
        return cls(varname=name, state=state)

    def to_dict(self):
        obj = {
            'op': 'var',
            'args': {
                'name': self.name,
                'state': self.state
            }
        }
        return obj


class Literal(Term):
    def __init__(self, name: str, entity_id: int) -> None:
        """
        The id of the entities, -1 for placeholder
        """
        self.name = name
        self.eid = entity_id

    @classmethod
    def parse(cls, term_obj):
        op = term_obj['op']
        assert op == 'ltr'
        args = term_obj['args']
        eid = args['eid']
        return cls(entity_id=eid)

    def to_dict(self):
        obj = {
            'op': 'ltr',
            'args': {
                'name': self.name,
                'eid': self.eid
            }
        }
        return obj


class Atom(Form):
    """
    Binary predicate or negated binary predicate
    """
    @classmethod
    def parse(cls, atom_obj):
        assert atom_obj['op'] in ['neg', 'pred']
        if atom_obj['op'] == 'neg':
            return Negation.parse(atom_obj)
        if atom_obj['op'] == 'pred':
            return BinaryPredicate.parse(atom_obj)


class BinaryPredicate(Atom):
    def __init__(self, relation_id: int, term1: Term, term2: Term) -> None:
        self.relation_id = relation_id
        self.term1 = term1
        self.term2 = term2

    @classmethod
    def parse(cls, atom_obj):
        op = atom_obj['op']
        assert op == 'pred'
        args = atom_obj['args']
        pid = args['pid']
        term1_obj = args['term1']
        term1 = Term.parse(term1_obj)
        term2_obj = args['term2']
        term2 = Term.parse(term2_obj)
        return cls(relation_id=pid, term1=term1, term2=term2)

    def to_dict(self):
        obj = {
            'op': 'pred',
            'args': {
                'pid': self.relation_id,
                'term1': self.term1.to_dict(),
                'term2': self.term2.to_dict()
            }
        }
        return obj


class Negation(Atom):
    def __init__(self, pred: BinaryPredicate) -> None:
        self.pred = pred

    @classmethod
    def parse(cls, atom_obj):
        op = atom_obj['op']
        assert op == 'neg'
        args = atom_obj['args']
        pred_obj = args['pred']
        return cls(pred_obj)

    def to_dict(self):
        obj = {
            'op': 'neg',
            'args': {'pred': self.pred.to_dict()}
        }
        return obj


class Conjunction(Form):
    def __init__(self, atoms: List[Atom]) -> None:
        self.atoms = atoms

    @classmethod
    def parse(cls, conj_obj):
        op = conj_obj['op']
        assert op == 'conj'
        args = conj_obj['args']
        atom_obj_list = args['atoms']
        atoms = [Atom.parse(atom_obj) for atom_obj in atom_obj_list]
        return cls(atoms)

    def to_dict(self):
        obj = {
            'op': 'conj',
            'args': {'atoms': [a.to_dict() for a in self.atoms]}
        }
        return obj


class Disjunction(Form):
    def __init__(self, atoms: List[Atom]) -> None:
        self.atoms = atoms

    @classmethod
    def parse(cls, disj_obj):
        op = disj_obj['op']
        assert op == 'disj'
        args = disj_obj['args']
        atom_obj_list = args['atoms']
        atoms = [Atom.parse(atom_obj) for atom_obj in atom_obj_list]
        return cls(atoms)

    def to_dict(self):
        obj = {
            'op': 'disj',
            'args': {'atoms': [a.to_dict() for a in self.atoms]}
        }
        return obj


class DNF(Form):
    def __init__(self, conjunctions: List[Conjunction]) -> None:
        self.conjunctions = conjunctions

    @classmethod
    def parse(cls, dnf_obj):
        op = dnf_obj['op']
        assert op == 'dnf'
        args = dnf_obj['args']
        conj_obj_list = args['conjs']
        conjunctions = [Conjunction.parse(conj_obj)
                        for conj_obj in conj_obj_list]
        return cls(conjunctions)

    def to_dict(self):
        obj = {
            'op': 'dnf',
            'args': {'conjs': [c.to_dict() for c in self.conjunctions]}
        }


class DNFFormula:
    """
    A base class for the string input of the entire formula structure
    """

    def __init__(self,
                 exist_vars: Dict[str, Variable],
                 free_vars: Dict[str, Variable],
                 literals: Dict[str, Variable],
                 dnf: DNF):
        self.exist_vars = exist_vars
        self.free_vars = free_vars
        self.literals = literals
        self.dnf = dnf

    @classmethod
    def loads(cls, s: str):
        obj = json.loads(s)

        evars = obj['EVAR'].split(',')
        fvars = obj['FVAR'].split(',')
        ltrs = obj['LTR'].split(',')
        dnf_obj = obj['DNF']
        dnf = DNF.parse(dnf_obj)
        return cls(evars, fvars, ltrs, dnf)

    def dumps(self):
        obj = {
            'EVAR': ','.join([str(k) for k in self.exist_vars]),
            'FVAR': ','.join([str(k) for k in self.free_vars]),
            'LTR': ','.join([str(k) for k in self.literals]),
            'DNF': self.dnf.to_dict()
        }
        return json.dumps(obj)


def sample_efo_dnf_query(p, q, r,
                         per,
                         l, k, pn):
    """
    args:
        term level:
            p: number of existential variables
            q: number of free variables
            r: number of literals
        atom level:
            per: probability of sampling the edge from er graph
                 each edge is an atom with relation to be filled
        conjuction level
            l: maximum number of conjunctive queries
            k: number of atoms per conjunctive queries
            pn: number of prossibility of the negation,
                since we don't have any negation before, 
                we won't suffer from the conflict
    """
    exist_vars = {f"ev:{i}": Variable(f"ev:{i}", Variable.EXIST)
                  for i in range(p)}

    free_vars = {f"fv:{i}": Variable(f"fv:{i}", Variable.FREE)
                 for i in range(q)}

    literals = {f"ltr:{i}": Literal(-1) for i in range(r)}

    terms = {}
    terms.update(exist_vars)
    terms.update(free_vars)
    terms.update(literals)

    print(terms)

    predicates = {}
    pred2termpair = {}
    term2pred = defaultdict(list)
    for k1 in terms:
        for k2 in terms:
            if k1 == k2:
                continue

            if random() > per:
                continue

            pid = f"pred:{len(pred2termpair)}"

            termpair = (k1, k2)
            pred2termpair[pid] = termpair

            _pred = BinaryPredicate(
                relation_id=-1, term1=terms[k1], term2=terms[k2])
            predicates[pid] = _pred

            term2pred[k1].append(pid)
            term2pred[k2].append(pid)

    pkeys = list(predicates.keys())
    conjunctions = {}
    conj2terms = defaultdict(set)
    for i_conj in range(l):
        conj_key = f"conj:{i_conj}"
        conj_atoms = []
        conj_pred_keys = sample(pkeys, k=k)
        for pred_key in conj_pred_keys:
            if random() < pn:
                atom = Negation(predicates[pred_key])
            else:
                atom = predicates[pred_key]
            conj_atoms.append(atom)
            for t in pred2termpair[pred_key]:
                if 'v' in t:
                    conj2terms[conj_key].add(t)
        conjunctions[conj_key] = Conjunction(atoms=conj_atoms)

    print(conj2terms)

    conj_graph = nx.Graph()
    for conj_k1 in conj2terms:
        for conj_k2 in conj2terms:
            if conj_k1 == conj_k2:
                continue
            if len(conj2terms[conj_k1].intersection(conj2terms[conj_k2])) > 0:
                conj_graph.add_edge(conj_k1, conj_k2)

    largest_conn_conj_comp = sorted(
        connected_components(conj_graph), key=len, reverse=True)[0]
    dnf = DNF(conjunctions=largest_conn_conj_comp)
    DNFFormula()
